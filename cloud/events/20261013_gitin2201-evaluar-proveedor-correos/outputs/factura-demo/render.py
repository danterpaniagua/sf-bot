#!/usr/bin/env python3
"""Fills the LaTeX ticket template with the data of a JSON file (demo for GITIN-2201).

The template (plantilla-factura.tex) holds no data: it reads `datos.tex`, which this script writes from the sections of the data
(meta, emisor, comprobante, cliente, detalle, descuentos_recargos, impuestos, pagos, totales, autorizacion, pie).
The data is a folder with one JSON file per section (datos/emisor.json, datos/detalle.json, ...), or a single JSON with all the sections.
Number format as on the printed ticket: decimal comma, no thousands separator, quantity with 3 decimals, 12-hour clock with "a. m." / "p. m.".
Usage: render.py <datos folder | datos.json> [--compile]
  --compile  also runs latexmk (pdflatex) into ./build/
Checks the amounts (items - discounts = total, net + exempt + iva = total, sum of iva rates = iva, payments = total) and prints a warning for each that does not match.
"""
import base64
import json
import subprocess
import sys
from datetime import datetime, timedelta, timezone
from decimal import Decimal
from pathlib import Path

HERE = Path(__file__).resolve().parent

LATEX = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def tex(text):
    return "".join(LATEX.get(c, c) for c in str(text))


def fixed(v, places):
    return f"{Decimal(str(v)):.{places}f}".replace(".", ",")


def money(v):
    return fixed(v, 2)


def macro(name, value):
    return f"\\newcommand{{\\{name}}}{{{value}}}\n"


def main():
    src = Path(sys.argv[1])
    if src.is_dir():  # one JSON file per section: <section>.json
        d = {p.stem: json.loads(p.read_text(encoding="utf-8")) for p in sorted(src.glob("*.json"))}
        missing = {"meta", "emisor", "comprobante", "cliente", "detalle", "impuestos", "pagos", "totales", "autorizacion", "pie"} - d.keys()
        if missing:
            sys.exit(f"missing sections in {src}: {sorted(missing)}")
    else:  # a single JSON with all the sections
        d = json.loads(src.read_text(encoding="utf-8"))
    e, c, cl, imp, aut = d["emisor"], d["comprobante"], d["cliente"], d["impuestos"], d["autorizacion"]
    out = ["%% Generated by render.py from %s. Do not edit.\n" % src.name]

    # the bill stores UTC; the printed date uses the stated offset
    sign = -1 if c["zona_horaria"].startswith("-") else 1
    hh, mm = c["zona_horaria"][1:].split(":")
    local = datetime.fromisoformat(c["fecha_utc"].replace("Z", "+00:00")).astimezone(timezone(sign * timedelta(hours=int(hh), minutes=int(mm))))

    # --- section: emisor
    for k, v in [("EmisorRazonSocial", e["razon_social"]), ("EmisorCuit", e["cuit"]), ("EmisorIibb", e["ingresos_brutos"]), ("EmisorDomicilio", e["domicilio"]),
                 ("EmisorInicio", e["inicio_actividades"]), ("EmisorCondicionIva", e["condicion_iva"])]:
        out.append(macro(k, tex(v)))

    # --- section: comprobante
    number = f"{c['punto_venta']:05d}-{c['numero']:08d}"
    out.append(macro("CompNombre", tex(c["tipo_nombre"])))
    out.append(macro("CompTipo", tex(c["tipo"])))
    out.append(macro("CompNumero", number))
    out.append(macro("CompFecha", local.strftime("%d/%m/%Y")))
    out.append(macro("CompHora", local.strftime("%I:%M:%S") + (" a. m." if local.hour < 12 else " p. m.")))

    # --- section: cliente
    doc = f"{cl['documento']}" if cl["documento"] else ""
    out.append(macro("ClienteNombre", tex(cl["nombre"])))
    out.append(macro("ClienteDocumento", f"({tex(doc)})" if doc else ""))
    out.append(macro("ClienteDomicilio", tex(cl["domicilio"])))

    # --- section: detalle
    rows = []
    items_total = Decimal(0)
    for it in d["detalle"]:
        items_total += Decimal(str(it["total"]))
        rows.append(f"{fixed(it['cantidad'], 3)} & {tex(it['descripcion'])} & {fixed(it['iva_pct'], 2)} & {money(it['precio_unitario'])} & {money(it['total'])} \\\\")
    out.append(macro("DetalleFilas", "\n".join(rows)))

    # --- section: descuentos y recargos (printed only when there are any)
    ds_total = Decimal(0)
    lines = []
    for x in d.get("descuentos_recargos") or []:
        sgn = -1 if x["tipo"] == "Discount" else 1
        ds_total += sgn * Decimal(str(x["importe"]))
        label = "DESCUENTO" if sgn < 0 else "RECARGO"
        lines.append(f"{label} {tex(x['descripcion'])}: {'-' if sgn < 0 else ''}{money(x['importe'])}\\\\")
    out.append(macro("DescuentoLineas", "\n".join(lines)))

    # --- section: impuestos
    out.append(macro("ImpNeto", money(imp["neto"])))
    out.append(macro("ImpExento", money(imp["exento"])))
    out.append(macro("ImpIva", money(imp["iva"])))
    out.append(macro("IvaLineas", "\n".join(f"IVA {fixed(a['tasa'], 2)}\\%: {money(a['importe'])}\\\\" for a in imp["alicuotas"])))

    # --- section: pagos
    out.append(macro("PagoFilas", "\n".join(f"{tex(p['medio'])} & {money(p['importe'])} \\\\" for p in d["pagos"])))
    pagos_total = sum(Decimal(str(p["importe"])) for p in d["pagos"])

    # --- section: totales
    total = Decimal(str(d["totales"]["total"]))
    out.append(macro("TotTotal", money(total)))

    # --- section: autorizacion (CAE and the fiscal QR URL; payload follows the field list of the QR specification, the values here are invented;
    #     the encoding was not validated against the fiscal validator)
    q = aut["qr"]
    payload = {"ver": q["ver"], "fecha": local.strftime("%Y-%m-%d"), "cuit": q["cuit"], "ptoVta": c["punto_venta"], "tipoCmp": c["codigo_arca"], "nroCmp": c["numero"],
               "importe": float(total), "moneda": q["moneda"], "ctz": q["ctz"], "tipoDocRec": q["tipoDocRec"], "nroDocRec": q["nroDocRec"], "tipoCodAut": q["tipoCodAut"],
               "codAut": int(aut["cae"])}
    url = "https://www.afip.gob.ar/fe/qr/?p=" + base64.urlsafe_b64encode(json.dumps(payload, separators=(",", ":")).encode()).decode()
    out.append(macro("AutCae", tex(aut["cae"])))
    out.append(macro("AutCaeVto", f"{aut['cae_vencimiento'][6:8]}/{aut['cae_vencimiento'][4:6]}/{aut['cae_vencimiento'][:4]}"))
    out.append(macro("QrUrl", "\\detokenize{" + url + "}"))

    # --- section: pie
    out.append(macro("PieMensaje", tex(d["pie"]["mensaje"])))
    out.append(macro("PieAviso", tex(d["pie"]["aviso"])))
    out.append(macro("VersionPlantilla", tex(d["meta"]["version_plantilla"])))

    (HERE / "datos.tex").write_text("".join(out), encoding="utf-8")
    print(f"datos.tex written; fiscal QR URL length {len(url)} characters ({len(payload)} fields)")

    # --- consistency checks
    tol = Decimal("0.01")
    if abs(items_total + ds_total - total) > tol:
        print(f"WARNING items {items_total} + discounts/surcharges {ds_total} != total {total}")
    if abs(Decimal(str(imp["neto"])) + Decimal(str(imp["exento"])) + Decimal(str(imp["iva"])) - total) > tol:
        print("WARNING net + exempt + iva != total")
    if abs(sum(Decimal(str(a["importe"])) for a in imp["alicuotas"]) - Decimal(str(imp["iva"]))) > tol:
        print("WARNING sum of iva rates != iva")
    if abs(pagos_total - total) > tol:
        print(f"WARNING payments {pagos_total} != total {total}")

    if "--compile" in sys.argv:
        subprocess.run(["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error", "-output-directory=build", "plantilla-factura.tex"], cwd=HERE, check=True,
                       stdout=subprocess.DEVNULL)
        print("PDF written to build/plantilla-factura.pdf")


if __name__ == "__main__":
    main()
